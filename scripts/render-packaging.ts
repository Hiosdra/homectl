// Renders the Homebrew formula and the winget manifests for one release. The archive
// checksums come from dist/SHA256SUMS, so the files point at exactly the bytes that the
// release publishes. Output goes to dist/packaging/.
//   bun scripts/render-packaging.ts
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const dist = join(root, "dist");
const repo = "Hiosdra/homectl";
const publisher = "Hiosdra";
const description = "Manage your homelab through KeePassXC and SSH.";

export interface Checksums {
  get(name: string): string;
}

// Parses sha256sum output: "<hex>  <name>" or "<hex> *<name>".
export function parseChecksums(text: string): Checksums {
  const map = new Map<string, string>();
  for (const line of text.split("\n")) {
    const match = /^([0-9a-f]{64}) [ *](.+)$/.exec(line.trim());
    if (match) map.set(match[2] as string, match[1] as string);
  }
  return {
    get(name) {
      const sum = map.get(name);
      if (!sum) throw new Error(`No checksum in SHA256SUMS for ${name}`);
      return sum;
    },
  };
}

export function archiveName(
  version: string,
  target: string,
  extension: string,
): string {
  return `homectl-${version}-${target}.${extension}`;
}

export function releaseUrl(version: string, name: string): string {
  return `https://github.com/${repo}/releases/download/v${version}/${name}`;
}

// The formula installs the release binary for the platform it runs on.
export function formula(version: string, sums: Checksums): string {
  const asset = (target: string) => {
    const name = archiveName(version, target, "tar.gz");
    return `      url "${releaseUrl(version, name)}"\n      sha256 "${sums.get(name)}"`;
  };
  return `# Generated by scripts/render-packaging.ts for homectl ${version}. Do not edit by hand.
class Homectl < Formula
  desc "${description.replace(/\.$/, "")}"
  homepage "https://github.com/${repo}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${asset("macos-arm64")}
    end
    on_intel do
${asset("macos-x64")}
    end
  end

  on_linux do
    on_arm do
${asset("linux-arm64")}
    end
    on_intel do
${asset("linux-x64")}
    end
  end

  def install
    bin.install "home-ctl"
  end

  def caveats
    <<~EOS
      homectl reads its vault through keepassxc-cli. Install KeePassXC, which provides it.
    EOS
  end

  test do
    assert_match "home-ctl", shell_output("#{bin}/home-ctl help")
  end
end
`;
}

export function wingetManifests(
  version: string,
  sums: Checksums,
): Record<string, string> {
  const id = `${publisher}.homectl`;
  const zip = archiveName(version, "windows-x64", "zip");
  const nested = `homectl-${version}-windows-x64\\home-ctl.exe`;
  const header = `PackageIdentifier: ${id}\nPackageVersion: ${version}\n`;
  const tail = "ManifestVersion: 1.6.0\n";
  return {
    [`${id}.yaml`]: `${header}DefaultLocale: en-US\nManifestType: version\n${tail}`,
    [`${id}.installer.yaml`]:
      `${header}Installers:\n` +
      `  - Architecture: x64\n` +
      `    InstallerType: zip\n` +
      `    NestedInstallerType: portable\n` +
      `    NestedInstallerFiles:\n` +
      `      - RelativeFilePath: ${nested}\n` +
      `        PortableCommandAlias: home-ctl\n` +
      `    InstallerUrl: ${releaseUrl(version, zip)}\n` +
      `    InstallerSha256: ${sums.get(zip).toUpperCase()}\n` +
      `ManifestType: installer\n${tail}`,
    [`${id}.locale.en-US.yaml`]:
      `${header}PackageLocale: en-US\nPublisher: ${publisher}\n` +
      `PublisherUrl: https://github.com/${publisher}\n` +
      `PackageName: homectl\nPackageUrl: https://github.com/${repo}\n` +
      `License: MIT\nShortDescription: ${description}\n` +
      `ManifestType: defaultLocale\n${tail}`,
  };
}

if (import.meta.main) {
  const { version } = JSON.parse(
    await readFile(join(root, "package.json"), "utf8"),
  ) as { version: string };
  const sums = parseChecksums(await readFile(join(dist, "SHA256SUMS"), "utf8"));
  const out = join(dist, "packaging");
  const winget = join(out, "winget");
  await mkdir(winget, { recursive: true });
  await writeFile(join(out, "homectl.rb"), formula(version, sums));
  for (const [name, text] of Object.entries(wingetManifests(version, sums)))
    await writeFile(join(winget, name), text);
  console.log(`Wrote the Homebrew formula and winget manifests to ${out}`);
}
